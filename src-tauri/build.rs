use std::path::PathBuf;

fn main() {
    emit_linux_binary_pins();
    tauri_build::build()
}

/// Generate the Linux sidecar integrity pins (`linux_pins.rs` in OUT_DIR).
///
/// The Windows build pins `aether.exe`/`xray.exe` digests as literals in
/// `process.rs`/`routing.rs`. The Linux pins cannot be literals in the
/// source tree in the same way: they are digests of the *Linux* upstream
/// payloads, which are only materialised after a digest-verified
/// download (`scripts/fetch-core-linux.sh` verifies each archive against
/// `scripts/linux-pins.json`, extracts it, hashes the payloads, and the
/// PKGBUILD/fetch step records the result). So the pin values arrive here
/// from one of two places, in priority order:
///
///   1. `AETHER_LINUX_SHA256` / `XRAY_LINUX_SHA256` environment variables
///      (the PKGBUILD exports them from its sha256sums-verified sources);
///   2. `linux-binary-pins.json` beside this manifest, written by the
///      fetch script (`{"aether": "<hex>", "xray": "<hex>"}`).
///
/// With neither present the constants are empty and the runtime refuses
/// to start the core (fail-closed, with instructions) rather than
/// executing an unpinned binary. On non-Linux targets the generated file
/// is simply never included.
fn emit_linux_binary_pins() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let pins_file = manifest.join("linux-binary-pins.json");
    println!("cargo:rerun-if-changed={}", pins_file.display());
    println!("cargo:rerun-if-env-changed=AETHER_LINUX_SHA256");
    println!("cargo:rerun-if-env-changed=XRAY_LINUX_SHA256");

    let from_file: serde_json::Value = std::fs::read_to_string(&pins_file)
        .ok()
        .and_then(|text| serde_json::from_str(&text).ok())
        .unwrap_or(serde_json::Value::Null);
    let pick = |env_name: &str, key: &str| -> String {
        let value = std::env::var(env_name)
            .ok()
            .filter(|v| !v.trim().is_empty())
            .or_else(|| from_file.get(key).and_then(|v| v.as_str()).map(str::to_string))
            .unwrap_or_default()
            .trim()
            .to_ascii_lowercase();
        // Only a real SHA-256 may become a pin; anything else is treated as
        // "no pin" so the runtime stays fail-closed instead of comparing
        // against garbage that could accidentally match nothing/everything.
        if value.len() == 64 && value.chars().all(|c| c.is_ascii_hexdigit()) {
            value
        } else {
            String::new()
        }
    };
    let aether = pick("AETHER_LINUX_SHA256", "aether");
    let xray = pick("XRAY_LINUX_SHA256", "xray");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default());
    let generated = format!(
        "// Generated by build.rs - see emit_linux_binary_pins(). Do not edit.\n\
         pub const AETHER_SHA256: &str = \"{aether}\";\n\
         pub const XRAY_SHA256: &str = \"{xray}\";\n"
    );
    let _ = std::fs::write(out_dir.join("linux_pins.rs"), generated);
}
